# Loss function — model kitna galat hai yeh measure karta hai
criterion = nn.CrossEntropyLoss()

# Training function
def train(epoch):
    model.train()
    total_loss    = 0
    correct       = 0
    total_samples = 0

    for batch in train_loader:
        batch = batch.to(device)

        # Step 1: Purani calculations clear karo
        optimizer.zero_grad()

        # Step 2: Forward pass — model prediction karo
        output = model(batch)

        # Step 3: Loss calculate karo
        loss = criterion(output, batch.y)

        # Step 4: Backward pass — galtiyan seekho
        loss.backward()

        # Step 5: Weights update karo
        optimizer.step()

        # Accuracy track karo
        pred           = output.argmax(dim=1)
        correct        += (pred == batch.y).sum().item()
        total_samples  += batch.y.size(0)
        total_loss     += loss.item()

    accuracy = correct / total_samples * 100
    avg_loss = total_loss / len(train_loader)
    return avg_loss, accuracy


# Testing function
def test():
    model.eval()
    correct       = 0
    total_samples = 0

    with torch.no_grad():
        for batch in test_loader:
            batch  = batch.to(device)
            output = model(batch)
            pred   = output.argmax(dim=1)
            correct       += (pred == batch.y).sum().item()
            total_samples += batch.y.size(0)

    return correct / total_samples * 100


