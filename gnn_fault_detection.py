from torch_geometric.nn import GCNConv, global_mean_pool
import torch.nn as nn

class CircuitGNN(nn.Module):
    def __init__(self, input_dim, hidden_dim, output_dim):
        """
        input_dim  = node features size (16 — one hot vocab size)
        hidden_dim = internal layer size (32)
        output_dim = number of classes (3 — Valid, Short, Floating)
        """
        super(CircuitGNN, self).__init__()

        # ── Graph Convolution Layers ───────────────────────────
        # Layer 1: har node apne direct neighbors se seekhta hai
        self.conv1 = GCNConv(input_dim, hidden_dim)

        # Layer 2: 2 hops door tak dekhta hai
        self.conv2 = GCNConv(hidden_dim, hidden_dim)

        # ── Classifier ────────────────────────────────────────
        # Graph level prediction ke liye
        self.classifier = nn.Linear(hidden_dim, output_dim)

        # Dropout — overfitting rokne ke liye
        self.dropout = nn.Dropout(p=0.3)

    def forward(self, data):
        x          = data.x           # Node features
        edge_index = data.edge_index  # Connections
        batch      = data.batch if hasattr(data, 'batch') and data.batch is not None \
                     else torch.zeros(x.size(0), dtype=torch.long)

        # ── Step 1: Message Passing ────────────────────────────
        # Har node apne neighbors ki info leta hai
        x = self.conv1(x, edge_index)
        x = F.relu(x)
        x = self.dropout(x)

        # ── Step 2: Deeper understanding ──────────────────────
        x = self.conv2(x, edge_index)
        x = F.relu(x)

        # ── Step 3: Graph level representation ────────────────
        # Sare nodes ka average leke poore graph ko ek vector mein compress karo
        x = global_mean_pool(x, batch)

        # ── Step 4: Classification ─────────────────────────────
        x = self.classifier(x)

        return x


