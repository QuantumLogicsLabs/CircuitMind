# Step 2: Circuit JSON ko Graph object mein convert karna

def circuit_to_graph(circuit_json: dict) -> Data:
    """
    Circuit JSON ko PyTorch Geometric Data object mein convert karta hai.

    Input:
        circuit_json: dict with components and connections
    Output:
        PyG Data object (x, edge_index, y)
    """
    components  = [c.lower() for c in circuit_json.get("components", [])]
    connections = circuit_json.get("connections", [])
    label       = circuit_json.get("label", 0)  # 0=Valid, 1=Short, 2=Floating

    # ── Node Features (One Hot Encoding) ──────────────────────
    node_features = torch.stack([encode_node(c) for c in components])

    # ── Edge Index ────────────────────────────────────────────
    edge_src = []  # from
    edge_dst = []  # to

    for connection in connections:
        # Parse "battery -> resistor -> led"
        if "->" in connection:
            nodes = [n.strip().lower() for n in connection.split("->")]
        elif "--" in connection:
            nodes = [n.strip().lower() for n in connection.split("--")]
        else:
            continue

        for i in range(len(nodes) - 1):
            src = nodes[i]
            dst = nodes[i + 1]

            # Component ka index dhundo
            if src in components and dst in components:
                edge_src.append(components.index(src))
                edge_dst.append(components.index(dst))

    # Edge index tensor
    if edge_src:
        edge_index = torch.tensor([edge_src, edge_dst], dtype=torch.long)
    else:
        edge_index = torch.zeros((2, 0), dtype=torch.long)

    # ── Label ─────────────────────────────────────────────────
    y = torch.tensor([label], dtype=torch.long)

    return Data(x=node_features, edge_index=edge_index, y=y)


