def predict_circuit(circuit_json: dict) -> str:
    model.eval()

    # Circuit ko graph mein convert karo
    graph = circuit_to_graph(circuit_json)

    # Sab tensors ek hi device pe bhejo
    graph.x          = graph.x.to(device)
    graph.edge_index = graph.edge_index.to(device)

    # Batch manually banao — ek graph hai toh sab zeros
    graph.batch = torch.zeros(
        graph.x.size(0),
        dtype=torch.long
    ).to(device)  # ← yahan .to(device) zaroori tha — yahi error thi

    # Prediction karo
    with torch.no_grad():
        output     = model(graph)
        prediction = output.argmax(dim=1).item()
        confidence = F.softmax(output, dim=1).max().item() * 100

    # Label decode karo
    labels = {
        0: "✅ Valid Circuit",
        1: "❌ Short Circuit",
        2: "⚠️  Floating Component"
    }

    result = labels[prediction]

    print(f"Circuit    : {circuit_json.get('circuit_name', 'Unknown')}")
    print(f"Prediction : {result}")
    print(f"Confidence : {confidence:.2f}%")
    print("-" * 40)

    return result


