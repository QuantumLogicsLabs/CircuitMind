def generate_valid_circuits(n=200):
    """200 valid circuits generate karo"""
    circuits = []

    for _ in range(n):
        power     = random.choice(POWER_SOURCES)
        mid       = random.choice(RESISTORS + TRANSISTORS)
        output    = random.choice(["led", "motor", "diode", "capacitor"])

        # Kabhi kabhi extra component add karo
        if random.random() > 0.5:
            components  = [power, mid, output]
            connections = [f"{power} -> {mid} -> {output}"]
        else:
            extra       = random.choice(RESISTORS)
            components  = [power, mid, extra, output]
            connections = [f"{power} -> {mid} -> {extra} -> {output}"]

        circuits.append({
            "components":  components,
            "connections": connections,
            "label":       0  # Valid
        })

    return circuits


def generate_short_circuits(n=200):
    """200 short circuits generate karo"""
    circuits = []

    for _ in range(n):
        power = random.choice(POWER_SOURCES)

        # 3 types of short circuits
        short_type = random.randint(1, 3)

        if short_type == 1:
            # Direct short — battery -> ground
            components  = [power, "ground"]
            connections = [f"{power} -> ground"]

        elif short_type == 2:
            # Wire through short — battery -> wire -> ground
            mid         = random.choice(["switch", "capacitor", "inductor"])
            components  = [power, mid, "ground"]
            connections = [f"{power} -> {mid} -> ground"]

        else:
            # Multi node short
            n1          = random.choice(["led", "diode", "capacitor"])
            n2          = random.choice(["switch", "inductor"])
            components  = [power, n1, n2, "ground"]
            connections = [f"{power} -> {n1} -> {n2} -> ground"]

        circuits.append({
            "components":  components,
            "connections": connections,
            "label":       1  # Short Circuit
        })

    return circuits


