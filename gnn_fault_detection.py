# Step 1: Component Vocabulary — One Hot Encoding ke liye
COMPONENT_VOCAB = {
    "battery": 0,
    "power_supply": 1,
    "resistor": 2,
    "capacitor": 3,
    "inductor": 4,
    "led": 5,
    "diode": 6,
    "zener_diode": 7,
    "transistor": 8,
    "npn_transistor": 9,
    "pnp_transistor": 10,
    "mosfet": 11,
    "op_amp": 12,
    "motor": 13,
    "switch": 14,
    "ground": 15
}

NUM_CLASSES = len(COMPONENT_VOCAB)  # 16

def encode_node(component_name: str) -> torch.Tensor:
    """
    Convert component name to One Hot Encoded vector.
    Unknown components get a zero vector.
    """
    idx = COMPONENT_VOCAB.get(component_name.lower(), -1)

    if idx == -1:
        # Unknown component — zero vector
        return torch.zeros(NUM_CLASSES)

    return F.one_hot(
        torch.tensor(idx),
        num_classes=NUM_CLASSES
    ).float()

