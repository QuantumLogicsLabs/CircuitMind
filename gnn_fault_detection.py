POWER_SOURCES    = ["battery", "power_supply"]
RESISTORS        = ["resistor"]
LEDS             = ["led", "diode", "zener_diode"]
TRANSISTORS      = ["transistor", "npn_transistor", "pnp_transistor", "mosfet"]
